def _snapshot_series() -> dict[str, list[int]]:
    rng = random.Random(7)
    n = len(MONTHS)

    def wobble(base: int, spread: int) -> list[int]:
        return [round((base + rng.randint(-spread, spread)) / 1000) * 1000 for _ in range(n)]

    def grow(start: int, monthly: int, ret: float, noise: float) -> list[int]:
        values, v = [], start
        for _ in range(n):
            v = v * (1 + ret + rng.uniform(-noise, noise)) + monthly
            values.append(round(v / 1000) * 1000)
        return values

    return {
        "A01": wobble(2_400_000, 500_000),
        "A02": wobble(1_900_000, 400_000),
        "A03": wobble(2_200_000, 600_000),
        "A04": [9_000_000 + 550_000 * i for i in range(n)],
        "A05": [12_900_000 + 100_000 * i for i in range(n)],
        "A06": [3_000_000 + 300_000 * i for i in range(n)],
        "I01": grow(31_000_000, 850_000, 0.008, 0.025),
        "I02": grow(17_500_000, 650_000, 0.007, 0.02),
        "I03": grow(13_500_000, 200_000, 0.010, 0.03),
        "P01": grow(21_000_000, 300_000, 0.006, 0.015),
        "P02": grow(11_500_000, 200_000, 0.004, 0.01),
        "P03": grow(37_000_000, 450_000, 0.004, 0.008),
        "R01": [780_000_000 + 2_000_000 * i for i in range(n)],
        "E01": [24_000_000 - 250_000 * i for i in range(n)],
        "L01": [292_000_000 - 600_000 * i for i in range(n)],
        "L02": [18_000_000 - 300_000 * i for i in range(n)],
        "L03": wobble(3_300_000, 600_000),
    }


def snapshots() -> list[tuple[str, str, int]]:
    series = _snapshot_series()
    return [(month, acc[0], series[acc[0]][i]) for i, month in enumerate(MONTHS) for acc in ACCOUNTS]


