def holdings() -> list[tuple]:
    base_index = MONTHS.index(BASE_MONTH)
    series = _snapshot_series()
    rows = []
    for acc, name, code, klass, weight, price, gain in HOLDING_PLAN:
        value = series[acc][base_index] * weight
        qty = max(1, round(value / price))
        avg = round(price / gain) if price > 1 else 1
        rows.append((acc, name, code, klass, qty, avg, price))
    return rows


